#!/usr/bin/env node

/**
 * ============================================================================
 * SCENTSPIRED THEME GUARDIAN — Guard: Region Literals
 * ============================================================================
 *
 * Shared code must not know which region it is serving.
 *
 * Every storefront-identifying value — the domain, the currency symbol, the
 * contact addresses — is regional DATA. It lives in regions/ and is resolved at
 * build time into snippets/region--active.liquid. A literal in shared code is a
 * coupling that silently ships the wrong value to every other region, which is
 * exactly how `'£' + price` came to render pound signs on dollar prices.
 *
 * This guard runs against the CORE, never against dist/: a compiled theme is
 * SUPPOSED to contain one region's resolved literals.
 *
 * Rules
 *   R1   identity domain  scentspired.<tld> in shared code
 *   R1c  CDN asset URL    an absolute upload pinned to one store
 *   R2   currency symbol  concatenated onto a price in JavaScript
 *   R3   hreflang         a language-region tag hardcoded in shared code
 *
 * Accepted exceptions are recorded in baseline-region-literals.json with the
 * reason they are accepted. The guard fails only on NEW violations, so
 * inherited debt is frozen rather than blocking, and cannot grow.
 *
 * Usage
 *   node tests/static/guard--region-literals.cjs            gate
 *   node tests/static/guard--region-literals.cjs --list     show each hit
 *   node tests/static/guard--region-literals.cjs --update   re-record baseline
 * ============================================================================
 */

const fs = require('fs');
const path = require('path');

// This guard always scans the CORE. A compiled theme in dist/ is SUPPOSED to
// contain one region's resolved literals, so --root lets the runner point here
// explicitly even while every other layer is pointed at a regional build.
const rootArg = process.argv.find((a) => a.startsWith('--root='));
const ROOT = path.resolve(
  rootArg ? rootArg.slice('--root='.length) : process.env.THEME_TARGET_DIR || process.cwd()
);
const BASELINE = path.join(__dirname, 'baseline-region-literals.json');

// Shared code only. regions/ is where literals belong; dist/ is compiled
// output; templates/ and config/ are merchant content, which regions overlay
// wholesale via the compiler.
const SCAN_DIRS = ['sections', 'snippets', 'blocks', 'layout', 'assets'];

// Generated by scripts/region-engine.cjs — resolved region data is their whole
// purpose, so they are the one place these literals are expected.
const GENERATED = new RegExp('^snippets/region--(active|registry)[.]liquid$');

const RULES = [
  {
    id: 'R1',
    label: 'identity domain',
    // A storefront domain. CDN asset URLs are a separate, milder case (R1c).
    pattern: /scentspired\.(?:co\.uk|com|ae)(?!\/cdn\/)/g,
    fix: "resolve it: {% render 'region--active', key: 'home_url' %}",
  },
  {
    id: 'R1c',
    label: 'CDN asset URL',
    // These resolve from any origin, so they are not a correctness bug today —
    // but they pin shared code to one store's uploads.
    pattern: /scentspired\.(?:co\.uk|com|ae)\/cdn\//g,
    fix: 'move the image to a setting, a metafield, or a region key',
  },
  {
    id: 'R2',
    label: 'currency symbol concatenated onto a price',
    pattern:
      /(['"`])\s*(?:£|\$|€|AED)\s*\1\s*\+|\+\s*(['"`])\s*(?:£|\$|€|AED)\s*\2|`\s*(?:£|\$|€|AED)\s*\$\{/g,
    fix: "read window.__STORE_CONFIG.currencySymbol, or key: 'currency_symbol'",
  },
  {
    id: 'R3',
    label: 'hardcoded hreflang',
    pattern: /["'](?:en-(?:gb|us|ae)|en_(?:GB|US|AE))["']/g,
    fix: "resolve it: {% render 'region--active', key: 'hreflang' %}",
  },
];

/**
 * Schema blocks are pure JSON and cannot hold Liquid, so a literal there is
 * unavoidable. Blank them out — preserving line count, so reported line numbers
 * stay accurate — before scanning.
 */
function stripSchema(src) {
  return src.replace(/\{%-?\s*schema\s*-?%\}[\s\S]*?\{%-?\s*endschema\s*-?%\}/g, (m) =>
    m.replace(/[^\n]/g, ' ')
  );
}

function toPosix(p) {
  return p.split(path.sep).join('/');
}

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if (/\.(liquid|js|json)$/.test(entry.name)) out.push(p);
  }
  return out;
}

console.log('');
console.log('╔══════════════════════════════════════════════════════════════╗');
console.log('║   SCENTSPIRED THEME GUARDIAN — Region Literal Guard          ║');
console.log('╚══════════════════════════════════════════════════════════════╝');
console.log(`  Target: ${ROOT}\n`);

const found = {}; // "rel::ruleId" -> count
const detail = [];

for (const dir of SCAN_DIRS) {
  for (const file of walk(path.join(ROOT, dir))) {
    const rel = toPosix(path.relative(ROOT, file));
    if (GENERATED.test(rel)) continue;

    const lines = stripSchema(fs.readFileSync(file, 'utf8')).split('\n');

    for (const rule of RULES) {
      let count = 0;
      lines.forEach((line, i) => {
        const hits = line.match(rule.pattern);
        if (!hits) return;
        count += hits.length;
        if (detail.length < 60) {
          detail.push({ rel, line: i + 1, rule, sample: line.trim().slice(0, 96) });
        }
      });
      if (count > 0) found[`${rel}::${rule.id}`] = count;
    }
  }
}

const baseline = fs.existsSync(BASELINE)
  ? JSON.parse(fs.readFileSync(BASELINE, 'utf8'))
  : { accepted: {} };
const accepted = baseline.accepted || {};

const regressions = [];
for (const [key, count] of Object.entries(found)) {
  const allowed = accepted[key] ? accepted[key].count : 0;
  if (count > allowed) regressions.push({ key, count, allowed });
}

const repaid = Object.keys(accepted).filter((k) => (found[k] || 0) < accepted[k].count);

const totalFound = Object.values(found).reduce((a, b) => a + b, 0);
const totalAccepted = Object.values(accepted).reduce((a, b) => a + b.count, 0);

console.log(`  Literals found:    ${totalFound}`);
console.log(`  Accepted baseline: ${totalAccepted}`);
console.log(`  New violations:    ${regressions.length}\n`);

if (process.argv.includes('--list') && detail.length) {
  for (const d of detail) {
    const key = `${d.rel}::${d.rule.id}`;
    console.log(`  [${accepted[key] ? 'accepted' : 'NEW'}] ${d.rel}:${d.line}  (${d.rule.id} ${d.rule.label})`);
    console.log(`         ${d.sample}`);
  }
  console.log('');
}

if (process.argv.includes('--update')) {
  const next = { accepted: {} };
  for (const [key, count] of Object.entries(found)) {
    const id = key.split('::')[1];
    const rule = RULES.find((r) => r.id === id);
    next.accepted[key] = {
      count,
      rule: rule.label,
      reason: accepted[key] ? accepted[key].reason : 'inherited — see TODO.md',
      fix: rule.fix,
    };
  }
  fs.writeFileSync(BASELINE, JSON.stringify(next, null, 2) + '\n');
  console.log(`  Baseline written: ${Object.keys(next.accepted).length} accepted entr(ies).\n`);
  process.exit(0);
}

if (repaid.length) {
  console.log('  ✅ Debt repaid since the baseline was taken:');
  for (const k of repaid) console.log(`     ${k}  ${accepted[k].count} -> ${found[k] || 0}`);
  console.log('     Re-run with --update to tighten the ratchet.\n');
}

if (regressions.length) {
  console.log('  ❌ New region literals in shared code:\n');
  for (const r of regressions) {
    const [rel, id] = r.key.split('::');
    const rule = RULES.find((x) => x.id === id);
    console.log(`     ${rel}  (${rule.label})`);
    console.log(`       found ${r.count}, allowed ${r.allowed}`);
    console.log(`       ${rule.fix}\n`);
  }
  console.log('  Shared code must not name a region. See regions/_defaults.json.\n');
  process.exit(1);
}

console.log('  ✅ No new region literals in shared code.\n');
process.exit(0);
